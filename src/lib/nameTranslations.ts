/**
 * Looks up a field/channel display name's full 11-language translation. Throws for an unmapped
 * string instead of silently falling back to English-only, so a newly added field with no
 * translation entry fails fast (`nameTranslations.test.ts` also asserts every field table's name
 * resolves cleanly, covering the case where a call site typos the lookup key).
 *
 * @param en - the canonical English name, exactly as used as this function's call-site argument
 */
export function translated(en: string): ioBroker.Translated {
    const rest = NAMES[en];
    if (!rest) {
        throw new Error(`Missing translation for "${en}" - add it to NAMES in nameTranslations.ts`);
    }
    return { en, ...rest };
}

